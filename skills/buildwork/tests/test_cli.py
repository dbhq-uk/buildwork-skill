def issues(github, *numbers, **bodies):
    """Open issues that each declare their own file, so none of them overlap."""
    for n in numbers:
        github.issue(n, f"issue {n}", body=bodies.get(f"b{n}", f"Change `src/f{n}.py`."))


def wave_numbers(payload):
    return [[item["issue"] for item in wave] for wave in payload["waves"]]


def remove_config(repo):
    repo.git("rm", "-q", ".github/buildwork.toml")
    repo.commit("no buildwork config")


