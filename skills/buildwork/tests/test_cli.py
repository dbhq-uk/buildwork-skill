def test_two_repositories_with_the_same_folder_name_keep_separate_sessions(repo, github, bw, tmp_path, home):
    other_gh = FakeGitHub(home=tmp_path / "gh-other", repo="owner/other")
    other = Repo(tmp_path / "elsewhere", isolated_env(home))
    assert other.root.name == repo.root.name
    for fake in (github, other_gh):
        issues(fake, 1, 2)

    env = {**os.environ, **isolated_env(home), **other_gh.env()}
    subprocess.run(
        [sys.executable, str(BUILDWORK), "plan", "--goal", "the other one", "--issues", "1,2", "--save"],
        cwd=other.root, env=env, capture_output=True, text=True, check=True,
    )
