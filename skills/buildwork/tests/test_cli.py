DESKWORK_ROADMAP = """\
# Roadmap

Generated by deskwork on 2026-09-17 from 6 open issues.
Order is reasoned, not computed. Every dependency shown is a declared GitHub link.

## Next

1. **#3** Third, reasoned first
   Nothing blocks it, and #4 waits on it.
2. **#1** First
3. **#2** Second

## Blocked

- **#4** Fourth - blocked by #3

## Triage - not yet in the roadmap

Filed by an agent and not yet reviewed. Listed, never ordered.

- #5 Filed by an agent
"""


def issues(github, *numbers, **bodies):
    """Open issues that each declare their own file, so none of them overlap."""
    for n in numbers:
        github.issue(n, f"issue {n}", body=bodies.get(f"b{n}", f"Change `src/f{n}.py`."))


def wave_numbers(payload):
    return [[item["issue"] for item in wave] for wave in payload["waves"]]


def remove_config(repo):
    repo.git("rm", "-q", ".github/buildwork.toml")
    repo.commit("no buildwork config")


# --- the opt-in gate --------------------------------------------------------

def test_no_config_means_no_action(repo, github, bw):
    remove_config(repo)
    issues(github, 1, 2)
    result = bw("plan", "--issues", "1,2")
    assert result.code == 1
    assert "buildwork is opt-in per repository" in result.err
    assert github.calls() == []


def test_enabled_false_means_no_action(repo, github, bw):
    repo.configure('enabled = false\nrunner = "paseo"\n')
    issues(github, 1, 2)
    result = bw("plan", "--issues", "1,2")
    assert result.code == 1
    assert "enabled = true" in result.err
    assert github.calls() == []


