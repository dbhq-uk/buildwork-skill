def merged_wave(repo, github, bw):
    """A wave of two where #1 was squash-merged on GitHub and #2 is still open."""
    issues(github, 1, 2)
    bw("plan", "--goal", "g", "--issues", "1,2", "--save")
    repo.branch("buildwork/issue-1-issue-1", {"src/f1.py": "x\n"})
    repo.branch("buildwork/issue-2-issue-2", {"src/f2.py": "x\n"})
    repo.merge_on_github("buildwork/issue-1-issue-1")
    github.pull(11, "buildwork/issue-1-issue-1", state="MERGED")
    github.pull(12, "buildwork/issue-2-issue-2")


